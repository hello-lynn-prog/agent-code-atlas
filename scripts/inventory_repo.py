#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""agent-code-atlas | inventory_repo.py — 只读仓库清单扫描。

用法:
    python inventory_repo.py <repo-path> --out <inventory.json> [选项]

选项:
    --include GLOB      限定分析范围(fnmatch 风格,* 跨目录;可多次)。
                        能覆盖某默认忽略目录的 pattern 会使其被重新扫描。
    --exclude GLOB      额外排除(可多次;文件级 exclude 优先于 include)。
    --max-file-size N   超过 N 字节的文件不读取内容、不统计行数(默认 2000000)。
    --follow-symlinks   跟随目录符号链接(默认关闭;指向仓库外的 symlink 永不跟随)。
    --include-generated 包含疑似生成代码(默认排除并记入 ignored)。

安全:只读;不执行目标项目代码;不把文件内容写入输出(仅元数据);
二进制只探测不解码;输出 UTF-8;路径兼容 Windows(内部统一用 / 分隔的相对路径)。
"""
from __future__ import annotations

import argparse
import datetime
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

SCHEMA_VERSION = "1.0"
TOOL = "inventory_repo 1.0"

DEFAULT_IGNORED_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "bower_components", "vendor", "dist",
    "build", "out", "target", "coverage", ".venv", "venv", "env", "__pycache__",
    ".idea", ".vscode", ".gradle", ".mypy_cache", ".pytest_cache", ".tox",
    "site-packages", ".next", ".nuxt", "Pods", "DerivedData", ".terraform",
    "cmake-build-debug", "cmake-build-release", ".cache",
}
GENERATED_DIR_NAMES = {"generated", "__generated__", "autogen", "gen"}
GENERATED_FILE_SUFFIXES = (
    ".pb.go", "_pb2.py", "_pb2_grpc.py", ".g.dart", ".pb.cc", ".pb.h",
    "_pb.js", "_pb.ts", ".designer.cs", ".generated.cs", ".generated.ts",
    ".generated.py", ".generated.go",
)
GENERATED_BYTES_MARKERS = (
    b"@generated", b"auto-generated", b"autogenerated", b"automatically generated",
    b"generated by", b"code generated", b"do not edit",
)
GENERATED_NAME_RE = re.compile(r"(^|[-_.])(generated|gen)[-_./]|\.generated\.", re.I)

LANGUAGES = {
    ".py": "Python", ".ts": "TypeScript", ".tsx": "TypeScript",
    ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript",
    ".go": "Go", ".rs": "Rust", ".java": "Java", ".kt": "Kotlin", ".kts": "Kotlin",
    ".cs": "C#", ".fs": "F#", ".rb": "Ruby", ".php": "PHP", ".swift": "Swift",
    ".c": "C", ".h": "C", ".cpp": "C++", ".cc": "C++", ".cxx": "C++", ".hpp": "C++",
    ".sh": "Shell", ".bash": "Shell", ".zsh": "Shell", ".ps1": "PowerShell",
    ".md": "Markdown", ".rst": "reStructuredText", ".adoc": "AsciiDoc",
    ".json": "JSON", ".yaml": "YAML", ".yml": "YAML", ".toml": "TOML", ".ini": "INI",
    ".sql": "SQL", ".html": "HTML", ".css": "CSS", ".scss": "SCSS", ".less": "Less",
    ".proto": "Protocol Buffers", ".vue": "Vue", ".svelte": "Svelte",
}

MANIFEST_NAMES = {
    "package.json", "pnpm-workspace.yaml", "lerna.json", "turbo.json", "nx.json",
    "rush.json", "tsconfig.json", "jsconfig.json", "pyproject.toml", "setup.py",
    "setup.cfg", "requirements.txt", "Pipfile", "Cargo.toml", "go.mod", "go.work",
    "pom.xml", "build.gradle", "build.gradle.kts", "settings.gradle",
    "settings.gradle.kts", "Makefile", "CMakeLists.txt", "Dockerfile",
    "composer.json", "Gemfile", "mix.exs", "nuget.config", "global.json",
}
MANIFEST_SUFFIXES = (".sln", ".csproj", ".fsproj", ".vbproj", ".gradle")

DOC_EXTS = {".md", ".rst", ".adoc"}
DOC_BASENAMES = {"readme", "changelog", "license", "licence", "contributing", "authors", "notice"}
TEST_DIR_NAMES = {"test", "tests", "__tests__", "spec", "specs", "testing"}
TEST_NAME_RE = re.compile(
    r"(^test_|_test\.(go|py|rs|java|cs)$|[.-](test|spec)[.-]|^test[a-z0-9_.-]*$|^conftest\.)",
    re.I,
)

MAX_IGNORED_LISTED = 200
READ_CHUNK = 65536


def norm_pattern(pat: str) -> str:
    return pat.replace("**", "*").strip("/")


def matches(rel: str, patterns) -> bool:
    return any(fnmatch.fnmatch(rel, norm_pattern(x)) for x in patterns)


def git_info(root: Path) -> dict:
    try:
        r = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                           capture_output=True, text=True, timeout=10)
        if r.returncode == 0 and r.stdout.strip():
            b = subprocess.run(["git", "-C", str(root), "rev-parse", "--abbrev-ref", "HEAD"],
                               capture_output=True, text=True, timeout=10)
            return {"is_git_repo": True, "revision": r.stdout.strip(),
                    "branch": b.stdout.strip() if b.returncode == 0 else None,
                    "detection": "git-cli"}
    except Exception:
        pass
    head = root / ".git" / "HEAD"
    if head.is_file():
        try:
            ref = head.read_text(encoding="utf-8", errors="replace").strip()
        except OSError:
            ref = ""
        if ref.startswith("ref: "):
            refname = ref[5:].strip()
            branch = refname.rsplit("/", 1)[-1]
            direct = root / ".git" / refname
            if direct.is_file():
                try:
                    sha = direct.read_text(encoding="utf-8", errors="replace").strip()
                    if re.fullmatch(r"[0-9a-f]{40}", sha):
                        return {"is_git_repo": True, "revision": sha, "branch": branch,
                                "detection": "head-file"}
                except OSError:
                    pass
            packed = root / ".git" / "packed-refs"
            if packed.is_file():
                try:
                    for line in packed.read_text(encoding="utf-8", errors="replace").splitlines():
                        parts = line.split()
                        if len(parts) == 2 and parts[1] == refname and re.fullmatch(r"[0-9a-f]{40}", parts[0]):
                            return {"is_git_repo": True, "revision": parts[0], "branch": branch,
                                    "detection": "packed-refs"}
                except OSError:
                    pass
        elif re.fullmatch(r"[0-9a-f]{40}", ref):
            return {"is_git_repo": True, "revision": ref, "branch": None, "detection": "head-file"}
    return {"is_git_repo": False, "revision": None, "branch": None, "detection": "none"}


class Scanner:
    def __init__(self, root: Path, args):
        self.root = root
        self.include = list(args.include or [])
        self.exclude = list(args.exclude or [])
        self.max_file_size = args.max_file_size
        self.follow_symlinks = args.follow_symlinks
        self.include_generated = args.include_generated
        self.warnings: list[str] = []
        self.ignored: dict[str, dict] = {}
        self.files: list[dict] = []
        self.dir_stats: dict[str, dict] = {}
        self.rescued_prefixes: list[str] = []

    def note_ignored(self, rel: str, reason: str) -> None:
        entry = self.ignored.setdefault(reason, {"count": 0, "paths": []})
        entry["count"] += 1
        if len(entry["paths"]) < MAX_IGNORED_LISTED:
            entry["paths"].append(rel)

    def dir_explicitly_included(self, rel_dir: str) -> bool:
        """include 是否显式覆盖某个默认忽略目录(如 node_modules/**),用于决定是否救回。"""
        for pat in self.include:
            norm = norm_pattern(pat)
            if fnmatch.fnmatch(rel_dir, norm) or norm.startswith(rel_dir + "/"):
                return True
        return False

    def dir_covered_by_include(self, rel_dir: str) -> bool:
        """include 模式是否可能覆盖该目录的子孙 —— 仅在给出了 --include 时才谈得上“覆盖”。"""
        if not self.include:
            return False
        first = rel_dir.split("/", 1)[0]
        for pat in self.include:
            norm = norm_pattern(pat)
            if fnmatch.fnmatch(rel_dir, norm):
                return True
            p1 = norm.split("/", 1)[0]
            if p1 == "*" or p1 == first:
                return True
        return False

    def file_in_include_scope(self, rel_file: str, rel_dir: str) -> bool:
        if not self.include:
            return True
        if matches(rel_file, self.include):
            return True
        if rel_dir and matches(rel_dir, self.include):
            return True
        return any(rel_file.startswith(px + "/") for px in self.rescued_prefixes)

    def run(self) -> dict:
        root_str = str(self.root)
        for dirpath, dirnames, filenames in os.walk(self.root, followlinks=self.follow_symlinks):
            rel_dir = "" if Path(dirpath) == self.root else Path(dirpath).relative_to(self.root).as_posix()
            keep: list[str] = []
            for d in sorted(dirnames):
                rel_child = d if rel_dir == "" else rel_dir + "/" + d
                full = os.path.join(dirpath, d)
                reason = None
                if os.path.islink(full):
                    real = os.path.realpath(full)
                    inside = real == root_str or real.startswith(root_str + os.sep)
                    if not self.follow_symlinks:
                        reason = "symlink (following disabled)"
                    elif not inside:
                        reason = "symlink escapes repository root"
                default_ignore = d in DEFAULT_IGNORED_DIRS or (
                    d in GENERATED_DIR_NAMES and not self.include_generated)
                if reason is None and default_ignore:
                    if self.dir_explicitly_included(rel_child):
                        self.rescued_prefixes.append(rel_child)
                    else:
                        reason = ("default ignored directory" if d in DEFAULT_IGNORED_DIRS
                                  else "generated directory")
                if reason is None and matches(rel_child, self.exclude) \
                        and not self.dir_covered_by_include(rel_child):
                    reason = "excluded by pattern"
                if reason:
                    self.note_ignored(rel_child, reason)
                else:
                    keep.append(d)
            dirnames[:] = keep

            for name in sorted(filenames):
                rel_file = name if rel_dir == "" else rel_dir + "/" + name
                full = os.path.join(dirpath, name)
                ext = Path(name).suffix.lower()
                if os.path.islink(full):
                    self.note_ignored(rel_file, "symlink file skipped")
                    continue
                if not self.file_in_include_scope(rel_file, rel_dir):
                    self.note_ignored(rel_file, "outside include scope")
                    continue
                if matches(rel_file, self.exclude):
                    self.note_ignored(rel_file, "excluded by pattern")
                    continue
                try:
                    size = os.path.getsize(full)
                except OSError as e:
                    self.warnings.append("cannot stat %s: %s" % (rel_file, e))
                    continue

                generated = (name.lower().endswith(GENERATED_FILE_SUFFIXES)
                             or bool(GENERATED_NAME_RE.search(name)))
                binary = False
                line_count = None
                head = b""
                if size > 0:
                    try:
                        with open(full, "rb") as fh:
                            head = fh.read(READ_CHUNK)
                    except OSError as e:
                        self.warnings.append("cannot read %s: %s" % (rel_file, e))
                        head = b""
                if head:
                    binary = b"\x00" in head
                    if not generated and not binary:
                        # 生成代码横幅位于文件头部,只看前 512 字节,避免源码正文
                        # (例如扫描器自身的标记列表)造成自匹配误报
                        low = head[:512].lower()
                        generated = any(m in low for m in GENERATED_BYTES_MARKERS)
                if generated and not self.include_generated:
                    self.note_ignored(rel_file, "generated")
                    continue

                if not binary and size <= self.max_file_size:
                    try:
                        with open(full, "rb") as fh:
                            raw = fh.read()
                        line_count = raw.count(b"\n") + (1 if raw and not raw.endswith(b"\n") else 0)
                        try:
                            raw.decode("utf-8")
                        except UnicodeDecodeError:
                            self.warnings.append("not valid UTF-8 (line count still computed): %s" % rel_file)
                    except OSError as e:
                        self.warnings.append("cannot read content of %s: %s" % (rel_file, e))
                elif not binary:
                    self.warnings.append("oversized, content not read (line_count null): %s" % rel_file)

                language = LANGUAGES.get(ext)
                if name.lower() == "dockerfile":
                    language = "Dockerfile"
                lower_base = Path(name).stem.lower()
                parts = rel_file.split("/")
                is_test = bool(TEST_NAME_RE.search(name)) or any(x in TEST_DIR_NAMES for x in parts[:-1])
                is_doc = ext in DOC_EXTS or "docs" in parts[:-1] or lower_base in DOC_BASENAMES
                is_manifest = name in MANIFEST_NAMES or name.lower().endswith(MANIFEST_SUFFIXES)

                self.files.append({
                    "path": rel_file,
                    "extension": ext,
                    "language": language,
                    "size": size,
                    "line_count": line_count,
                    "binary": binary,
                    "generated": generated,
                    "test": is_test,
                    "documentation": is_doc,
                    "manifest": is_manifest,
                })
                stat = self.dir_stats.setdefault(rel_dir or ".", {"files": 0, "bytes": 0})
                stat["files"] += 1
                stat["bytes"] += size

        self.files.sort(key=lambda f: f["path"])
        langs: dict[str, dict] = {}
        for f in self.files:
            if f["language"]:
                entry = langs.setdefault(f["language"], {"files": 0, "bytes": 0, "lines": 0})
                entry["files"] += 1
                entry["bytes"] += f["size"]
                entry["lines"] += f["line_count"] or 0
        if not self.files:
            self.warnings.append("no files collected — check repo path / include patterns")
        return {
            "files": self.files,
            "directory_statistics": dict(sorted(self.dir_stats.items())),
            "languages": dict(sorted(langs.items(), key=lambda kv: -kv[1]["bytes"])),
            "ignored": dict(sorted(self.ignored.items())),
            "warnings": self.warnings,
        }


def main() -> int:
    ap = argparse.ArgumentParser(description="agent-code-atlas read-only repository inventory")
    ap.add_argument("repo", help="repository root path")
    ap.add_argument("--out", required=True, help="output inventory.json path")
    ap.add_argument("--include", action="append", default=[], metavar="GLOB")
    ap.add_argument("--exclude", action="append", default=[], metavar="GLOB")
    ap.add_argument("--max-file-size", type=int, default=2_000_000, metavar="BYTES")
    ap.add_argument("--follow-symlinks", action="store_true")
    ap.add_argument("--include-generated", action="store_true")
    args = ap.parse_args()

    root = Path(args.repo).resolve()
    if not root.is_dir():
        print("error: repository path is not a directory: %s" % root, file=sys.stderr)
        return 2
    out = Path(args.out)
    if out.parent and not out.parent.exists():
        out.parent.mkdir(parents=True, exist_ok=True)

    result = Scanner(root, args).run()
    inventory = {
        "schema_version": SCHEMA_VERSION,
        "tool": TOOL,
        "repository_root": str(root),
        "repository_name": root.name,
        "git": git_info(root),
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "scan": {
            "file_count": len(result["files"]),
            "total_bytes": sum(f["size"] for f in result["files"]),
            "included_patterns": args.include,
            "excluded_patterns": args.exclude,
            "max_file_size": args.max_file_size,
            "follow_symlinks": args.follow_symlinks,
            "include_generated": args.include_generated,
        },
        "files": result["files"],
        "directory_statistics": result["directory_statistics"],
        "languages": result["languages"],
        "ignored": result["ignored"],
        "warnings": result["warnings"],
    }
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(inventory, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print("inventory: %d files, %d warnings -> %s" % (len(result["files"]), len(result["warnings"]), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
